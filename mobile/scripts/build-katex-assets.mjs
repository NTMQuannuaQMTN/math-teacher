/**
 * Generates src/components/math/katexAssets.generated.ts from the installed
 * `katex` package: the minified JS plus the CSS with every font inlined as a
 * data: URI. Native maths rendering (WebView) then works fully offline and
 * never loads code from a third-party CDN. Runs on postinstall.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const dist = dirname(require.resolve("katex/dist/katex.min.js"));
const out = join(dirname(fileURLToPath(import.meta.url)), "../src/components/math/katexAssets.generated.ts");

const js = readFileSync(join(dist, "katex.min.js"), "utf8");
const css = readFileSync(join(dist, "katex.min.css"), "utf8").replace(
  /src:url\(fonts\/([\w-]+)\.woff2\) format\("woff2"\)(?:,url\([^)]+\) format\("[^"]+"\))*/g,
  (_, name) => {
    const data = readFileSync(join(dist, "fonts", `${name}.woff2`)).toString("base64");
    return `src:url(data:font/woff2;base64,${data}) format("woff2")`;
  },
);
if (/url\(fonts\//.test(css)) throw new Error("Some KaTeX fonts were not inlined");

const version = JSON.parse(readFileSync(join(dist, "../package.json"), "utf8")).version;
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/build-katex-assets.mjs from katex@${version}. Do not edit.\n` +
    `export const KATEX_VERSION = ${JSON.stringify(version)};\n` +
    `export const KATEX_JS = ${JSON.stringify(js)};\n` +
    `export const KATEX_CSS = ${JSON.stringify(css)};\n`,
);
console.log(`katex assets written (${Math.round((js.length + css.length) / 1024)} KB)`);
