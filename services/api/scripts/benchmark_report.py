"""Summarise every benchmark run (benchmarks/results/*.jsonl) into benchmarks/REPORT.md.

Run: uv run python scripts/benchmark_report.py
The latest run also gets a per-topic table and the list of items that are wrong or not verified, which is where
accuracy work should start.
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from decimal import Decimal
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[3]
RESULTS = ROOT / "benchmarks" / "results"
REPORT = ROOT / "benchmarks" / "REPORT.md"
STATUSES = ("VERIFIED", "PARTIALLY_VERIFIED", "UNVERIFIED", "INCORRECT", "UNSOLVED")


def load(path: Path) -> list[dict[str, Any]]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def summary(rows: list[dict[str, Any]]) -> dict[str, Any]:
    done = [r for r in rows if r.get("verification")]
    # Every item with a checkable reference counts; a failed run counts as wrong.
    graded = [r for r in rows if r.get("has_expected")]
    costs = [Decimal(r["cost_sgd"]) for r in done if r.get("cost_sgd")]
    secs = [float(r["seconds"]) for r in done if r.get("seconds")]
    statuses = Counter(r["verification"] for r in done)
    figures = Counter(r["figure"] for r in done if r.get("figure"))
    return {
        "items": len(rows), "errors": len(rows) - len(done),
        "correct": sum(1 for r in graded if r.get("correct")), "graded": len(graded),
        "false_verified": [r["id"] for r in graded if r.get("verification") == "VERIFIED" and not r.get("correct")],
        "statuses": statuses,
        "compliant": sum(1 for r in done if r.get("curriculum") in ("COMPLIANT", "COMPLIANT_WITH_WARNINGS")),
        "cost_mean": sum(costs) / len(costs) if costs else Decimal(0), "cost_total": sum(costs, Decimal(0)),
        "secs_mean": sum(secs) / len(secs) if secs else 0.0, "figures": figures, "done": len(done),
    }


def pct(n: int, d: int) -> str:
    return f"{n}/{d} ({100 * n / d:.0f}%)" if d else "–"


def main() -> None:
    runs = sorted(RESULTS.glob("*.jsonl"))
    lines = ["# Benchmark report", "", "Generated by `services/api/scripts/benchmark_report.py` from "
             "`benchmarks/results/`. Authentic items only (see `benchmarks/README.md`).", "",
             "| Run | Items | Correct (checkable) | VERIFIED | Partial | Unverified | Incorrect | Unsolved | "
             "False VERIFIED | Compliant | Mean cost (SGD) | Mean time |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for path in runs:
        s = summary(load(path))
        st = s["statuses"]
        lines.append(f"| {path.stem} | {s['items']} | {pct(s['correct'], s['graded'])} | "
                     + " | ".join(str(st.get(k, 0)) for k in STATUSES)
                     + f" | {len(s['false_verified'])} | {pct(s['compliant'], s['done'])} | "
                       f"{s['cost_mean']:.4f} | {s['secs_mean']:.0f} s |")
    if runs:
        latest = load(runs[-1])
        by_topic: dict[str, list[dict[str, Any]]] = defaultdict(list)
        for row in latest:
            by_topic[row.get("topic", "?")].append(row)
        lines += ["", f"## Latest run by topic ({runs[-1].stem})", "",
                  "| Topic | Items | " + " | ".join(STATUSES) + " | Compliant | Mean cost (SGD) |",
                  "| --- | --- | " + " | ".join("---" for _ in STATUSES) + " | --- | --- |"]
        for topic, rows in sorted(by_topic.items()):
            s = summary(rows)
            lines.append(f"| {topic} | {s['items']} | " + " | ".join(str(s["statuses"].get(k, 0)) for k in STATUSES)
                         + f" | {pct(s['compliant'], s['done'])} | {s['cost_mean']:.4f} |")
        s = summary(latest)
        if s["figures"]:
            lines += ["", "Geometry figures (formalization → drawable construction): "
                      + ", ".join(f"{k} {v}" for k, v in s["figures"].most_common()) + "."]
        lines += ["", "## Where to start improving", "",
                  "Wrong answers on checkable items, then unverified or unsolved items:", ""]
        for row in latest:
            if row.get("has_expected") and not row.get("correct"):
                lines.append(f"- **wrong**: `{row['id']}` ({row.get('verification')}) answers "
                             f"{json.dumps(row.get('machine_answers'), ensure_ascii=False)[:160]}")
        for row in latest:
            if row.get("verification") in ("UNSOLVED", None) or row.get("error"):
                lines.append(f"- **unsolved/error**: `{row['id']}` {row.get('error') or ''}")
        non_compliant = [r for r in latest if r.get("curriculum") == "NON_COMPLIANT"]
        for row in non_compliant:
            rules = [f["rule"] if isinstance(f, dict) else f for f in row.get("curriculum_findings", [])]
            lines.append(f"- **non-compliant**: `{row['id']}` {', '.join(rules)}")
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {REPORT} ({len(runs)} runs)")


if __name__ == "__main__":
    main()
